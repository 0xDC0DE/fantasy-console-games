"""Validate the family's word list and sync its word-only puzzles to PICO-8."""

from itertools import permutations
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
LIST = HERE / "tweeklank-woordenlijst.md"
CART = HERE / "Tweeklanken.p8"
PAIRS = ("eu", "au", "ei", "ou", "oe", "ij", "ui", "ie")
SAME_SOUND = ({"ei", "ij"}, {"au", "ou"})
START = "-- word bank begin (generated by word_bank.py)"
END = "-- word bank end"


def completions(pattern, cell, line_number):
    prefix, suffix = pattern.split("__")
    found = []
    for word in (part.strip() for part in cell.split(",")):
        if not word:
            continue
        if "ng" in word or "nk" in word:
            raise ValueError(f"line {line_number}: excluded ng/nk word {word!r}")
        if (len(word) != len(prefix) + len(suffix) + 2
                or not word.startswith(prefix) or not word.endswith(suffix)):
            raise ValueError(f"line {line_number}: {word!r} does not fit {pattern!r}")
        pair = word[len(prefix):len(prefix) + 2]
        if pair not in PAIRS:
            raise ValueError(f"line {line_number}: unsupported pair in {word!r}")
        if pair not in found:
            found.append(pair)
    return found


def read_list():
    rows = []
    seen = set()
    for line_number, line in enumerate(LIST.read_text(encoding="utf-8").splitlines(), 1):
        if not line.startswith("|") or line.startswith("| Pattern") or line.startswith("|---"):
            continue
        cells = [part.strip() for part in line.strip().strip("|").split("|")]
        cells += [""] * (3 - len(cells))
        pattern, valid_cell, hard_cell = cells[:3]
        if not re.fullmatch(r"[a-z]*__[a-z]*", pattern):
            raise ValueError(f"line {line_number}: invalid pattern {pattern!r}")
        if pattern in seen:
            raise ValueError(f"line {line_number}: duplicate pattern {pattern!r}")
        seen.add(pattern)
        hard = completions(pattern, hard_cell, line_number)
        valid = [pair for pair in completions(pattern, valid_cell, line_number)
                 if pair not in hard]
        if not valid:
            raise ValueError(f"line {line_number}: no valid completion for {pattern!r}")
        # The difficulty column wins when a word appears in both columns.
        rows.append((pattern, valid, hard))
    if not rows:
        raise ValueError("The word list has no puzzle rows")
    return guard_confusing_choices(rows)


def guard_confusing_choices(rows):
    """Use only listed words to block sound-alike distractors."""
    listed_words = {
        prefix + pair + suffix
        for pattern, valid, hard in rows
        for prefix, suffix in (pattern.split("__"),)
        for pair in (*valid, *hard)
    }
    guarded = []
    for pattern, valid, hard in rows:
        prefix, suffix = pattern.split("__")
        blocked = list(hard)
        for pair in (*valid, *hard):
            for group in SAME_SOUND:
                if pair in group:
                    other = next(candidate for candidate in group if candidate != pair)
                    if other not in valid and other not in blocked:
                        blocked.append(other)
        if suffix.endswith(("d", "t")):
            other_end = "t" if suffix.endswith("d") else "d"
            for pair in PAIRS:
                if pair in valid or pair in blocked:
                    continue
                sound_alike = prefix + pair + suffix[:-1] + other_end
                if sound_alike in listed_words:
                    blocked.append(pair)
        guarded.append((pattern, valid, blocked))
    return guarded


def compatible(a, b):
    return {a, b} not in SAME_SOUND


def three_letter_count(rows):
    """The three-letter section comes first and remains in the later pool."""
    count = 0
    longer_seen = False
    for pattern, _, _ in rows:
        letters = len(pattern) - 2
        if letters == 1:
            if longer_seen:
                raise ValueError("Three-letter words must come first")
            count += 1
        elif letters < 2:
            raise ValueError(f"Word pattern {pattern!r} is shorter than three letters")
        else:
            longer_seen = True
    if count < 8:
        raise ValueError("The first section needs at least eight three-letter patterns")
    return count


def validate_choices(rows):
    """Check shuffled choices and find puzzles limited to two options."""
    two_choice_only = set()
    for index, (pattern, valid, hard) in enumerate(rows, 1):
        for first in valid:
            remaining = [pair for pair in PAIRS if pair != first and pair not in hard]
            for order in permutations(remaining):
                for target_count in (2, 3):
                    chosen = [first]
                    good_count = 1
                    for pair in order:
                        if len(chosen) == target_count:
                            break
                        if not all(compatible(pair, earlier) for earlier in chosen):
                            continue
                        good = pair in valid
                        if good and good_count >= target_count - 1:
                            continue
                        chosen.append(pair)
                        good_count += good
                    if len(chosen) != target_count or good_count == target_count:
                        if target_count == 2:
                            raise ValueError(f"Cannot make two choices for {pattern}")
                        two_choice_only.add(index)
    return sorted(two_choice_only)


def sync_word_bank():
    rows = read_list()
    two_choice_only = validate_choices(rows)
    short_count = three_letter_count(rows)
    if any(index > short_count for index in two_choice_only):
        raise ValueError("A longer word cannot make three choices")
    limited = ",".join(map(str, two_choice_only))
    lines = [START, f"three_letter_count={short_count}",
             f"two_choice_only={{{limited}}}", "word_words={"]
    for pattern, valid, hard in rows:
        prefix, suffix = pattern.split("__")
        good = ",".join(str(PAIRS.index(pair) + 1) for pair in valid)
        bad = ",".join(str(PAIRS.index(pair) + 1) for pair in hard)
        blocked = f",{{{bad}}}" if bad else ""
        lines.append(f' {{"{prefix}","{suffix}",{{{good}}}{blocked}}},')
    lines += ["}", END]
    source = CART.read_text(encoding="ascii")
    if source.count(START) != 1 or source.count(END) != 1:
        raise ValueError("Cartridge is missing unique word bank markers")
    start = source.index(START)
    end = source.index(END, start) + len(END)
    result = source[:start] + "\n".join(lines) + source[end:]
    if result != source:
        CART.write_text(result, encoding="ascii")
    return len(rows)


if __name__ == "__main__":
    print(f"Synced {sync_word_bank()} word-only puzzles to {CART}")
